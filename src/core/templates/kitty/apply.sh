#!/usr/bin/env bash
set -euo pipefail

kitty_config_dir="${XDG_CONFIG_HOME:-$HOME/.config}/kitty"
config_file="$kitty_config_dir/kitty.conf"
theme_file="$kitty_config_dir/themes/ptm.conf"
include_line='include themes/ptm.conf'

# kitty loads only the first kitty.conf it finds, so a new user file would hide one in XDG_CONFIG_DIRS.
find_system_config() {
    local dir dirs
    IFS=: read -ra dirs <<<"${XDG_CONFIG_DIRS:-/etc/xdg}"
    for dir in "${dirs[@]}"; do
        if [ -n "$dir" ] && [ -f "$dir/kitty/kitty.conf" ]; then
            printf '%s\n' "$dir/kitty/kitty.conf"
            return 0
        fi
    done
    return 1
}

if [ ! -f "$config_file" ] && system_config="$(find_system_config)"; then
    echo "Warning: not creating $config_file because it would hide $system_config; add 'include $theme_file' to your kitty config to apply the PTM theme" >&2
    exit 0
fi

mkdir -p "$kitty_config_dir"
touch "$config_file"

tmp_file="$(mktemp "${config_file}.tmp.XXXXXX")"

cleanup() {
    rm -f "$tmp_file"
}
trap cleanup EXIT

awk -v include_line="$include_line" '
    # Remove the block generated by `kitty +kitten themes`.
    /^# BEGIN_KITTY_THEME[[:space:]]*$/ {
        in_theme_block = 1
        changed = 1
        next
    }

    in_theme_block && /^# END_KITTY_THEME[[:space:]]*$/ {
        in_theme_block = 0
        next
    }

    in_theme_block {
        next
    }

    # Strip legacy PTM template includes to prevent conflicting theme overrides
    /^[[:space:]]*include[[:space:]]+(\.\/)?current-theme\.conf[[:space:]]*$/ {
        changed = 1
        next
    }
    /^[[:space:]]*include[[:space:]]+.*plasma-colors\.conf[[:space:]]*$/ {
        changed = 1
        next
    }

    # Preserve the first existing include exactly where it is.
    # Remove only duplicate copies.
    $0 == include_line {
        if (include_seen) {
            changed = 1
            next
        }

        include_seen = 1
        print
        next
    }

    {
        print
    }

    END {
        # Add the include only if it did not already exist.
        if (!include_seen) {
            print include_line
        }
    }
' "$config_file" >"$tmp_file"

# Replace kitty.conf only if its contents actually changed. Write through a symlink
# instead of replacing it with a regular file via mv.
if ! cmp -s "$config_file" "$tmp_file"; then
    cat "$tmp_file" >"$config_file"
fi

# Clean up legacy template artifacts from older PTM versions if present
rm -f "$kitty_config_dir/current-theme.conf" \
      "$kitty_config_dir/dark-theme.auto.conf" \
      "$kitty_config_dir/light-theme.auto.conf" \
      "$kitty_config_dir/no-preference-theme.auto.conf" 2>/dev/null || true

if [[ ! -f "$theme_file" ]]; then
    printf 'Warning: Kitty theme file not found: %s\n' "$theme_file" >&2
fi

# Reload all running Kitty instances via signal
pkill -USR1 -x kitty >/dev/null 2>&1 || true

# Live-reload running Kitty sessions via OSC color escape sequences across all open pts
ttys=()
for kpid in $(pgrep -x kitty 2>/dev/null || true); do
    for child in $(pgrep -P "$kpid" 2>/dev/null || true); do
        child_tty="$(ps -o tty= -p "$child" 2>/dev/null | tr -d ' ' || true)"
        if [ -n "$child_tty" ] && [ "$child_tty" != "?" ]; then
            ttys+=("/dev/$child_tty")
        fi
    done
done

if [ ${#ttys[@]} -gt 0 ] && [ -f "$theme_file" ]; then
    unique_ttys=($(printf '%s\n' "${ttys[@]}" | sort -u))
    osc_seq=""
    while read -r key val; do
        case "$key" in
            background) osc_seq+="$(printf "\033]11;%s\a" "$val")" ;;
            foreground) osc_seq+="$(printf "\033]10;%s\a" "$val")" ;;
            cursor)     osc_seq+="$(printf "\033]12;%s\a" "$val")" ;;
            color[0-9]|color1[0-5])
                idx="${key#color}"
                osc_seq+="$(printf "\033]4;%s;%s\a" "$idx" "$val")"
                ;;
        esac
    done < "$theme_file"

    for tty_path in "${unique_ttys[@]}"; do
        if [ -w "$tty_path" ]; then
            printf "%s" "$osc_seq" > "$tty_path" 2>/dev/null || true
        fi
    done
fi
